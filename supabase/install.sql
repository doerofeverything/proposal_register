  "referenceProposalNumber" text,
  "originalProposalType" text,
  "referenceProposalType" text,
  "sourceRow" text,
  "sourceIndex" text,
  unique ("baseId", revision),
  check (
    (revision = 0 and "proposalType" = 'New') or
    (revision > 0 and "proposalType" = 'Revised')
